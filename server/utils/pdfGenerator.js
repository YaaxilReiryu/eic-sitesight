const PDFDocument = require('pdfkit')
const path = require('path')
const fs = require('fs')

function generateDefectPDF(report) {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 50, size: 'A4' })
      const buffers = []

      doc.on('data', (chunk) => buffers.push(chunk))
      doc.on('end', () => resolve(Buffer.concat(buffers)))
      doc.on('error', reject)

      // ── Header ──────────────────────────────────────────────
      doc.rect(0, 0, doc.page.width, 80).fill('#1d4ed8')
      doc.fillColor('white')
         .fontSize(20)
         .font('Helvetica-Bold')
         .text('EIC Advance Sdn Bhd', 50, 20)
      doc.fillColor('#bfdbfe')
         .fontSize(10)
         .font('Helvetica')
         .text('Site Defect Compliance Report', 50, 46)
      doc.fillColor('white')
         .fontSize(10)
         .text(`Report ID: #${report.id}`, 50, 62)

      doc.moveDown(3)

      // ── Status Badge ─────────────────────────────────────────
      const statusColor = report.status === 'Done' ? '#16a34a'
        : report.status === 'Ongoing' ? '#2563eb' : '#d97706'

      doc.roundedRect(50, doc.y, 100, 22, 4).fill(statusColor)
      doc.fillColor('white')
         .fontSize(10)
         .font('Helvetica-Bold')
         .text(report.status, 55, doc.y - 17, { width: 90, align: 'center' })

      doc.moveDown(1.5)

      // ── Section: Defect Information ──────────────────────────
      doc.fillColor('#1e3a8a')
         .fontSize(13)
         .font('Helvetica-Bold')
         .text('Defect Information')
      doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#bfdbfe').lineWidth(1).stroke()
      doc.moveDown(0.5)

      const fields = [
        ['Defect Type', report.defect_type],
        ['Materials Required', report.materials_required || 'Not specified'],
        ['Notes', report.notes || 'None'],
        ['Submission Date', new Date(report.submitted_at).toLocaleString('en-MY')],
      ]

      fields.forEach(([label, value]) => {
        doc.fillColor('#6b7280').fontSize(9).font('Helvetica').text(label.toUpperCase())
        doc.fillColor('#111827').fontSize(11).font('Helvetica').text(value)
        doc.moveDown(0.6)
      })

      // ── Section: GPS Location ────────────────────────────────
      doc.moveDown(0.5)
      doc.fillColor('#1e3a8a')
         .fontSize(13)
         .font('Helvetica-Bold')
         .text('GPS Location')
      doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#bfdbfe').lineWidth(1).stroke()
      doc.moveDown(0.5)

      doc.fillColor('#6b7280').fontSize(9).font('Helvetica').text('COORDINATES')
      doc.fillColor('#111827').fontSize(11).font('Helvetica')
         .text(`${Number(report.latitude).toFixed(6)}, ${Number(report.longitude).toFixed(6)}`)
      doc.moveDown(0.4)
      doc.fillColor('#2563eb').fontSize(9)
         .text(`View on Map: https://maps.google.com/?q=${report.latitude},${report.longitude}`,
           { link: `https://maps.google.com/?q=${report.latitude},${report.longitude}`, underline: true })

      // ── Section: Defect Photo ────────────────────────────────
      if (report.photo_path) {
        const photoPath = path.join(__dirname, '../uploads', report.photo_path)
        if (fs.existsSync(photoPath)) {
          doc.moveDown(1)
          doc.fillColor('#1e3a8a')
             .fontSize(13)
             .font('Helvetica-Bold')
             .text('Defect Photo')
          doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#bfdbfe').lineWidth(1).stroke()
          doc.moveDown(0.5)
          doc.image(photoPath, 50, doc.y, { width: 495, height: 250, fit: [495, 250] })
        }
      }

      // ── Footer ───────────────────────────────────────────────
      doc.moveDown(2)
      doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#e5e7eb').lineWidth(1).stroke()
      doc.moveDown(0.5)
      doc.fillColor('#9ca3af')
         .fontSize(8)
         .font('Helvetica')
         .text(
           `Generated by EIC-SiteSight Platform • ${new Date().toLocaleString('en-MY')} • EIC Advance Sdn Bhd, Putrajaya`,
           { align: 'center' }
         )

      doc.end()
    } catch (err) {
      reject(err)
    }
  })
}

module.exports = { generateDefectPDF }
